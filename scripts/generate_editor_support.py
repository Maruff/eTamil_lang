"""Regenerate the VS Code extension's language data from the compiler itself.

The extension used to carry a hand-written keyword list. It drifted: by the
time anyone checked, 67 of the lexer's 201 keywords were missing from the
grammar and 28 romanized spellings were the pre-`Z` scheme, so the spellings
the editor highlighted were exactly the ones the compiler rejected. Nothing
could have caught that, because nothing derived one from the other.

Now everything that can be derived is. Run from the repository root after
changing the token list, the builtins, or nUlakam:

    python scripts/generate_editor_support.py
    python scripts/generate_editor_support.py --check   # CI: fail on drift

Written outputs:

    eTamil_Code/syntaxes/etamil.tmLanguage.json   TextMate grammar
    eTamil_Code/src/generated/language-data.ts    completions, hover, symbols

Three things are read, and nothing is duplicated by hand:

  lexer.rs        every keyword and every spelling of it, grouped by the
                  section comments the lexer already uses.
  parser.rs       `is_identifier_like` and `is_type_token`, which decide
                  whether a word is reserved or is usable as a name. This is
                  the distinction the old grammar got backwards — it
                  highlighted மாறி and நிலை as declarations when both are
                  ordinary names to the parser.
  interpreter.rs  the builtin functions, with their arity and doc comment.
  nUlakam/*.qmz   the standard library's own செயல் definitions.

What is *not* derived is the shape of each statement — `(cond) எனில் { }`
cannot be inferred from a token name. Those templates live in SNIPPETS below
and are the one part of this file that must be kept true by hand; every one
of them is exercised by tests/test_snippets.py.
"""

