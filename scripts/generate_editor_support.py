def read_tokens() -> list[dict]:
    """Every keyword in lexer.rs, in declaration order, tagged with section."""
    tokens: list[dict] = []
    section = ""
    for line in LEXER.read_text(encoding="utf-8").splitlines():
        heading = re.match(r"^\s*//\s*---\s*(.+?)\s*---", line)
        if heading:
            # "Control Flow (Your Updated Syntax)" -> "Control Flow"
            section = re.sub(r"\s*\(.*?\)\s*$", "", heading.group(1)).strip()
            continue
        entry = re.search(r'#\[regex\("([^"]+)"\)\]\s*(\w+)', line)
        if entry:
            tokens.append(
                {
                    "token": entry.group(2),
                    "forms": entry.group(1).split("|"),
                    "section": section,
                }
            )
    if not tokens:
        die(f"no keywords found in {LEXER}")
    return tokens


def read_parser_classification() -> tuple[set[str], set[str]]:
    """The parser's own answer to "may this word be a name?".

    Returns (not_a_name, type_keywords). Derived rather than restated: the
    grammar's job is to reflect the parser, and a second hand-kept copy of
    this list is what went wrong last time.
    """
    source = PARSER.read_text(encoding="utf-8")

    body = re.search(
        r"fn is_identifier_like\(token: &Token\) -> bool \{(.*?)\n    \}",
        source,
        re.S,
    )
    if not body:
        die("could not find is_identifier_like in parser.rs")
    # Every arm ending in `=> false` names words that cannot be identifiers.
    not_a_name: set[str] = set()
    for arm in re.findall(r"^(.*?)=>\s*false\s*,", body.group(1), re.M):
        not_a_name.update(re.findall(r"Token::(\w+)", arm))
    if not not_a_name:
        die("is_identifier_like matched no `=> false` arms")

    types = re.search(
        r"fn is_type_token\(token: &Token\) -> bool \{(.*?)\n    \}", source, re.S
    )
    if not types:
        die("could not find is_type_token in parser.rs")
    type_keywords = set(re.findall(r"Token::(\w+)", types.group(1)))

    return not_a_name, type_keywords


def read_builtins() -> list[dict]:
    """Host builtins from the interpreter's call_builtin match."""
    lines = INTERPRETER.read_text(encoding="utf-8").splitlines()
    builtins: list[dict] = []

    for index, line in enumerate(lines):
        arm = re.match(r'^\s+("(?:[^"]+)"(?:\s*\|\s*"[^"]+")+)\s*=>\s*\{', line)
        if not arm:
            continue
        forms = re.findall(r'"([^"]+)"', arm.group(1))
        if not is_tamil(forms[0]):
            continue  # a string match that is not a builtin name

        # The doc convention here is a comment block directly above the arm,
        # whose first useful line reads `// நீளம்(...) — what it does`.
        doc: list[str] = []
        cursor = index - 1
        while cursor >= 0:
            stripped = lines[cursor].strip()
            if not stripped.startswith("//"):
                break
            doc.append(stripped.lstrip("/").strip())
            cursor -= 1
        doc.reverse()

        # Arity, where the arm states it.
        arity = None
        for probe in lines[index : index + 6]:
            want = re.search(r"expect_args\(name,\s*&args,\s*(\d+)\)", probe)
            if want:
                arity = int(want.group(1))
                break

        builtins.append(
            {
                "name": forms[0],
                "forms": forms,
                "doc": pick_doc(doc, forms[0]),
                "arity": arity,
            }
        )

    if not builtins:
        die("no builtins found in interpreter.rs")
    return builtins


def unmark(text: str) -> str:
    """Drop the `__` marks an English comment carries.

    A comment written in English is wrapped `// __like this__` so that an
    editor showing the file in the eTamil font knows to draw those letters as
    Latin rather than as Tamil — `docs/reference/SCRIPT_RULES.md`. The marks
    are addressed to the editor, not to whoever reads a tooltip, so they come
    off here. Without this every hover in the extension grew a `__` at each
    end.
    """
    text = text.strip()
    if text.startswith("__") and text.endswith("__") and len(text) > 4:
        return text[2:-2].strip()
    return text


def full_doc(doc_lines: list[str], name: str) -> str:
    """The whole comment block, for a consumer that wants more than a summary.

    `pick_doc` returns one line because that is what a hover shows: an editor
    popup repeating four paragraphs is worse than one that says the thing.
    A search index wants the opposite. The rationale under a summary — why
    மாத_இறுதி asks மாத_நாட்கள் instead of adding a month and stepping back — is
    what distinguishes one function from its neighbours, and returning a single
    line meant an index saw none of it.

    Dividers and the bare signature line are dropped, for the same reasons
    pick_doc skips them: neither says anything about what the function does.
    """
    kept = []
    for line in doc_lines:
        if not line or line.startswith("---") or line.startswith("==="):
            continue
        close = line.find(")")
        if line.startswith(name) and close != -1 and line[close + 1 :].strip(" .:—-") == "":
            continue
        kept.append(line)
    return chr(10).join(kept)


def pick_doc(doc_lines: list[str], name: str) -> str:
    """The line of a comment block that describes `name`, else the first.

    The library's convention is a bare signature line above the prose:

        // அலகுக்குச்_செலவு(மொத்தச்_செலவு, அலகுகள்)
        //
        // __The cost per unit. தவறு when there are no units, because...__

    Both lines start with the name, and returning the first one returned the
    signature — which the caller can already see — while the sentence that
    explains the function never left the file. 271 of 708 stdlib entries were
    indexed that way, so a search for what a function *does* had nothing to
    match on for more than a third of the library.

    A line that is only a signature describes nothing, so it is skipped in
    favour of one that says something, and kept only as a last resort where
    there is nothing else.
    """

    def only_a_signature(line: str) -> bool:
        if not line.startswith(name):
            return False
        close = line.find(")")
        # Anything after the closing paren beyond punctuation is prose.
        return close == -1 or line[close + 1 :].strip(" .:—-") == ""

    # Best: the line that names the function and then says something about it.
    for line in doc_lines:
        if line.startswith(name) and not only_a_signature(line):
            return line
    # Otherwise any prose, skipping dividers and signature-only lines.
    for line in doc_lines:
        if line and not line.startswith("---") and not only_a_signature(line):
            return line
    # A signature is still better than nothing.
    for line in doc_lines:
        if line and not line.startswith("---"):
            return line
    return ""


def read_stdlib() -> list[dict]:
    """Every செயல் the standard library defines, with params and doc."""
    functions: list[dict] = []

    # Sort the POSIX string rather than the Path. Path ordering is
    # case-insensitive on Windows and case-sensitive everywhere else, so
    # sorting Path objects makes the output depend on which machine ran
    # this — aNi.qmz and AvaNam.qmz swap places, and CI then rejects a
    # file that was correct when it was generated.
    for path in sorted(NULAKAM.rglob("*.qmz"), key=lambda p: p.as_posix()):
        # uqavi/ holds the worked examples, not the library. A helper a sample
        # defines to make its own point is not something an editor should offer
        # as a completion, and three of them had already got in this way.
        if "uqavi" in path.relative_to(NULAKAM).parts:
            continue
        module = path.relative_to(ROOT).as_posix()
        lines = path.read_text(encoding="utf-8").splitlines()

        for index, line in enumerate(lines):
            if not re.match(rf"^\s*(?:செயல்|ceyal|_fn)\s+{IDENT}\s*\(", line):
                continue
            # A long parameter list wraps. Join forward to the closing paren,
            # or the 14 widest functions in the accounting framework — the
            # ones most worth completing — go missing.
            header = line
            probe = index
            while ")" not in header and probe + 1 < len(lines):
                probe += 1
                header += " " + lines[probe].strip()
            define = re.match(
                rf"^\s*(?:செயல்|ceyal|_fn)\s+({IDENT})\s*\((.*?)\)", header
            )
            if not define:
                continue
            name = define.group(1)
            params = [p.strip() for p in define.group(2).split(",") if p.strip()]

            doc: list[str] = []
            cursor = index - 1
            while cursor >= 0:
                stripped = lines[cursor].strip()
                if not stripped.startswith("//"):
                    break
                doc.append(unmark(stripped.lstrip("/").strip()))
                cursor -= 1
            doc.reverse()

            functions.append(
                {
                    "name": name,
                    "forms": [name],
                    "params": params,
                    "doc": pick_doc(doc, name),
                    # The whole block as well as the summary. Nothing written
                    # into eTamil_Code reads this; it is for an index, which
                    # wants every word there is about a function.
                    "detail": full_doc(doc, name),
                    "module": module,
                    # 1-based, so Go to Definition can open the library at the
                    # செயல் line rather than at the top of the file.
                    "line": index + 1,
                }
            )

    if not functions:
        die(f"no செயல் definitions found under {NULAKAM}")
    return functions


# --------------------------------------------------------------------------
# Classification
# --------------------------------------------------------------------------
def classify(tokens: list[dict]) -> list[dict]:
    not_a_name, type_keywords = read_parser_classification()

    for entry in tokens:
        token = entry["token"]
        # `take_name` accepts a token when it is identifier-like *and* not a
        # type keyword, so a type keyword is equally unusable as a name even
        # though is_identifier_like says nothing about it. Reporting only the
        # first half would tell an author that `சொல் உரை = "x";` is fine.
        entry["reserved"] = token in not_a_name or token in type_keywords
        entry["no_syntax"] = token in NO_SYNTAX

        if token in TOKEN_SCOPES:
            entry["scope"] = TOKEN_SCOPES[token]
        elif token in type_keywords:
            entry["scope"] = "storage.type.etamil"
        elif not entry["reserved"]:
            # Usable as a name, so not a keyword however domain-specific it
            # looks. `support.` reads as vocabulary, not syntax.
            entry["scope"] = "support.type.domain.etamil"
        else:
            entry["scope"] = SECTION_SCOPES.get(
                entry["section"], "keyword.other.etamil"
            )

    return tokens


# --------------------------------------------------------------------------
# Grammar
# --------------------------------------------------------------------------
def word_pattern(forms: list[str]) -> str:
    """A \\b-anchored alternation, longest first.

    Longest-first is not strictly required — the trailing \\b already forces
    the regex to backtrack from கோப்பு to கோப்பு_திற — but relying on that is
    a trap for whoever edits this next.
    """
    ordered = sorted(set(forms), key=lambda form: (-len(form), form))
    return r"\b(?:" + "|".join(re.escape(f) for f in ordered) + r")\b"


def build_grammar(tokens: list[dict], builtins: list[dict], stdlib: list[dict]) -> dict:
    by_scope: dict[str, list[str]] = {}
    for entry in tokens:
        by_scope.setdefault(entry["scope"], []).extend(entry["forms"])

    patterns: list[dict] = [
        # Comments first, and line comments only: the lexer skips `//...` and
        # has no block comment at all, so a /* */ rule greyed out code the
        # compiler then rejected with a lex error.
        # An English comment that opens with `__` and has not closed yet.
        #
        # This rule comes first, and it is a block rule rather than a line
        # rule, because Rule 2's marks go at the ends of the *sentence*: `__`
        # on the first comment line and `__` on the last. The previous version
        # nested a single-line `__.+?__` inside the line-comment rule below,
        # so a sentence spanning two lines left each of them holding one
        # unmatched mark, neither matched, and the English in between was
        # coloured as ezuqqu. docs/reference/SCRIPT_RULES.md.
        #
        # `end` has two alternatives and the order matters. The closing mark
        # wins where there is one. Otherwise the region stops at the start of
        # a line that is not a comment — a zero-width lookahead, which ends
        # the rule without consuming anything — so one unclosed `__` cannot
        # colour the rest of the file English.
        {
            "name": "comment.line.double-slash.etamil",
            "contentName": "meta.english.comment.etamil",
            "begin": r"//[ 	]*__",
            "end": r"__|^(?=[ 	]*[^ 	/])",
            "beginCaptures": {"0": {"name": "punctuation.definition.comment.etamil"}},
        },
        {
            "name": "comment.line.double-slash.etamil",
            "begin": "//",
            "end": "$",
            "beginCaptures": {"0": {"name": "punctuation.definition.comment.etamil"}},
            # A marked run that does not start the comment — `// kaZakku
            # __two words__ mudivu`. Two such runs on one line are two, which
            # is why this stays non-greedy, and why the block rule above is
            # anchored to `//` and cannot swallow them.
            "patterns": [
                {
                    "name": "meta.english.comment.etamil",
                    "match": r"__.+?__",
                }
            ],
        },
        # Only double quotes. eTamil has no single-quoted string, and the old
        # grammar's `'...'` rule turned any stray apostrophe into a phantom
        # string that swallowed the rest of the file.
        {
            "name": "string.quoted.double.etamil",
            "begin": '"',
            "end": '"',
            "beginCaptures": {"0": {"name": "punctuation.definition.string.begin.etamil"}},
            "endCaptures": {"0": {"name": "punctuation.definition.string.end.etamil"}},
            "patterns": [
                # The five the lexer decodes.
                {"name": "constant.character.escape.etamil", "match": r'\\[ntr"\\]'},
                # Anything else keeps both characters rather than being an
                # escape, which is worth showing as different from the above.
                {"name": "invalid.illegal.unknown-escape.etamil", "match": r"\\."},
            ],
        },
        # Percentage before plain number, and no trailing \b: `%` is not a
        # word character, so `%\b` could never match before `;` or a newline
        # and every percentage literal fell through to the number rule.
        {
            "name": "constant.numeric.percentage.etamil",
            "match": r"\b\d+(?:\.\d+)?%",
        },
        {
            "name": "constant.numeric.decimal.etamil",
            # No digit separators: the lexer rejects 1_000, and highlighting
            # it as a number advertised a literal that does not exist.
            "match": r"\b\d+(?:\.\d+)?\b",
        },
        # `செயல் peyar(` — the definition, so the name reads as a definition
        # rather than as a call. The keyword is captured separately: a theme
        # colours keyword.*, not meta.*, so scoping the whole match as meta
        # would leave செயல் uncoloured in exactly the place it matters.
        {
            "name": "meta.function.declaration.etamil",
            "match": rf"({word_pattern(next(t['forms'] for t in tokens if t['token'] == 'Function'))})\s+({IDENT})",
            "captures": {
                "1": {"name": "keyword.declaration.function.etamil"},
                "2": {"name": "entity.name.function.etamil"},
            },
        },
        # A record key, before the keyword groups: `{வரி: 100}` produces the
        # field வரி, and a field name is data — what the author typed — not
        # the Tax keyword. Ordering this after the keyword patterns scoped it
        # as domain vocabulary instead.
        #
        # Safe ahead of the keywords because `:` appears nowhere else in the
        # grammar's reach: a quoted key and a path like "/kaNakku/:id" are
        # both already inside the string rule above.
        {
            "match": rf"({IDENT})\s*(:)",
            "captures": {
                "1": {"name": "variable.other.member.etamil"},
                "2": {"name": "punctuation.separator.key-value.etamil"},
            },
        },
    ]

    # Keyword groups. Ordered most specific first so a more precise scope
    # always wins at a given position.
    scope_order = [
        "keyword.control.conditional.etamil",
        "keyword.control.loop.etamil",
        "keyword.control.flow.return.etamil",
        "keyword.control.import.etamil",
        "keyword.control.route.etamil",
        "keyword.control.every.etamil",
        "keyword.control.etamil",
        "keyword.declaration.function.etamil",
        "keyword.operator.logical.etamil",
        "keyword.other.io.etamil",
        "keyword.other.response.etamil",
        "storage.type.etamil",
        "constant.language.boolean.etamil",
        "constant.language.null.etamil",
        "support.constant.http-method.etamil",
        "support.constant.database.etamil",
        "support.function.fileio.etamil",
        "support.function.database.etamil",
        "keyword.other.database.etamil",
        "keyword.other.sql.etamil",
        "keyword.other.http.etamil",
        "keyword.other.security.etamil",
        "keyword.other.etamil",
        "support.type.domain.etamil",
    ]
    missing = set(by_scope) - set(scope_order)
    if missing:
        die(f"scope(s) not placed in scope_order: {sorted(missing)}")

    for scope in scope_order:
        if scope in by_scope:
            patterns.append({"name": scope, "match": word_pattern(by_scope[scope])})

    # Functions the host provides, then the ones nUlakam defines. Both go
    # before the generic call rule so a known function keeps its own scope.
    patterns.append(
        {
            "name": "support.function.builtin.etamil",
            "match": word_pattern([f for b in builtins for f in b["forms"]]),
        }
    )
    patterns.append(
        {
            "name": "support.function.stdlib.etamil",
            "match": word_pattern([f["name"] for f in stdlib]),
        }
    )

    patterns.extend(
        [
            {
                "name": "entity.name.function.etamil",
                "match": rf"{IDENT}(?=\s*\()",
            },
            {
                "name": "variable.other.member.etamil",
                "match": rf"(?<=\.)\s*{IDENT}",
            },
            {"name": "keyword.operator.comparison.etamil", "match": r"==|!=|>=|<=|>|<"},
            {"name": "keyword.operator.assignment.etamil", "match": r"="},
            {"name": "keyword.operator.concat.etamil", "match": r"&"},
            {"name": "keyword.operator.arithmetic.etamil", "match": r"[+\-*/]"},
            # `?` — unwrap a சரி or hand the தவறு to the caller.
            {"name": "keyword.operator.try.etamil", "match": r"\?"},
            # A name marked English by Rule 1. Last of the name rules, so a
            # keyword (`_length`), a builtin and an nUlakam function keep the
            # scope that says what they are; what is left is the variables and
            # parameters people write.
            {
                "name": "variable.other.english.etamil",
                "match": rf"(?<![{TAMIL}\w])_[{TAMIL}\w]+",
            },
            {"name": "punctuation.accessor.etamil", "match": r"\."},
            {"name": "punctuation.terminator.etamil", "match": r";"},
            {"name": "punctuation.separator.etamil", "match": r","},
            {"name": "meta.brace.round.etamil", "match": r"[()]"},
            {"name": "meta.brace.square.etamil", "match": r"[\[\]]"},
            {"name": "meta.brace.curly.etamil", "match": r"[{}]"},
            {"name": "variable.other.etamil", "match": IDENT},
        ]
    )

    return {
        "$schema": "https://raw.githubusercontent.com/martinring/tmlanguage/master/tmlanguage.json",
        "name": "eTamil",
        "scopeName": "source.etamil",
        "fileTypes": ["qmz"],
        "_generated": BANNER,
        "patterns": patterns,
        "repository": {},
    }


